// New course material → raw/. The working folder is the inbox: every file not yet on the site ends in
// " [NOT YET IN STUDY SITE]". This script finds those files (video skipped — never copied or committed), maps each to
// its raw/<unit>/week-NN/ name (each unit's naming; tag and "for Code" dropped), and says per week whether it is a NEW
// week or a REGENERATION (and whether that week is currently thin). Copy, never move; never overwrite.
//
//   node scripts/inbox.mjs                 dry run: the plan, grouped by week
//   node scripts/inbox.mjs --copy          copy the files into raw/ (skips any that already exist)
//   node scripts/inbox.mjs --status        per unit and week: on the site? thin? transcript? → docs/pending-material.md
//   node scripts/inbox.mjs --untag <week-id> [...]   AFTER the week is live and verified: drop the tag from that week's
//                                          source files in the working folder (rename only; video keeps its tag)
// Working folder: $STUDY_INBOX, default "/Users/deveshramanan/University Semester 2 (Working Folder)".
import { readdirSync, statSync, existsSync, mkdirSync, copyFileSync, renameSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import yaml from 'js-yaml';

const INBOX = process.env.STUDY_INBOX || '/Users/deveshramanan/University Semester 2 (Working Folder)';
const TAG = ' [NOT YET IN STUDY SITE]';
const VIDEO = /\.(mp4|mov|m4a|m4v|webm|mkv)$/i;
// Working-folder unit folder → [site unit id, raw folder, the "Unit - " prefix its file names carry]
export const UNITS = {
  International: ['laws2000', 'laws2000-pil', 'International - '],
  Jurisprudence: ['laws2100', 'laws2100-juris', 'Jurisprudence - '],
  Torts: ['laws2400', 'laws2400-torts', 'Torts - '],
  Marketing: ['mgmt2094', 'mgmt2094-sci', null],
};

function walk(dir, acc = []) {
  if (!existsSync(dir)) return acc;
  for (const e of readdirSync(dir)) {
    if (e.startsWith('.')) continue;
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, acc); else acc.push(p);
  }
  return acc;
}

/** raw/ file name for a working-folder file, following each unit's existing convention. */
export function rawName(folder, file) {
  let n = file.replace(TAG, '').replace(' for Code', '');
  const [, , prefix] = UNITS[folder];
  if (folder === 'Torts') {
    // "Torts - Week 08 - Lecture 1 Slides.pptx" → "Topic 8 Lecture 1.pptx"; other types keep their title.
    const m = n.match(/^Torts - Week (\d+) - (.*)$/);
    if (m) n = `Topic ${+m[1]} ${m[2].replace(/^Lecture (\d) Slides/, 'Lecture $1')}`;
  } else if (prefix && n.startsWith(prefix)) n = n.slice(prefix.length);
  return n;
}

/** Every tagged, non-video file in the four unit folders, with where it goes and what it does to its week. */
export function plan() {
  const out = [];
  for (const [folder, [unit, rawDir]] of Object.entries(UNITS)) {
    for (const p of walk(join(INBOX, folder))) {
      const file = p.split('/').pop();
      if (!file.includes(TAG) || VIDEO.test(file)) continue;
      const parent = p.split('/').at(-2);
      const wk = parent.match(/^Week (\d+)$/)?.[1];
      const sub = wk ? `week-${wk.padStart(2, '0')}` : /unit-wide/i.test(parent) ? 'unit-wide' : null;
      if (!sub) { out.push({ src: p, unit, problem: `not in a "Week NN" or "Unit-wide" folder: ${relative(INBOX, p)}` }); continue; }
      const dest = join('raw', rawDir, sub, rawName(folder, file));
      const weekId = wk ? `${unit}-w${wk.padStart(2, '0')}` : `${unit}-unit-wide`;
      out.push({ src: p, dest, unit, weekId, exists: existsSync(dest) });
    }
  }
  return out;
}

const weekFile = (id) => join('src/content/weeks', `${id}.md`);
const isThin = (id) => existsSync(weekFile(id)) && /^thin: true/m.test(readFileSync(weekFile(id), 'utf8'));

function showPlan(items) {
  const byWeek = new Map();
  for (const i of items) byWeek.set(i.weekId ?? 'problems', [...(byWeek.get(i.weekId ?? 'problems') ?? []), i]);
  for (const [w, list] of [...byWeek].sort()) {
    const kind = w === 'problems' ? 'CHECK BY HAND' : w.endsWith('unit-wide') ? 'unit-wide context' : existsSync(weekFile(w)) ? `REGENERATE${isThin(w) ? ' (currently thin)' : ''}` : 'NEW WEEK';
    console.log(`\n${w}  →  ${kind}`);
    for (const i of list) console.log(i.problem ? `  ! ${i.problem}` : `  ${i.exists ? '= already in raw:' : '+'} ${i.dest}`);
  }
}

const args = process.argv.slice(2);
if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (args[0] === '--status') {
    const lines = ['# Pending material (generated by `node scripts/inbox.mjs --status`)', '',
      'What each week was built from, and what is still missing. Thin weeks name the material that would fix them.', ''];
    for (const [, [unit, rawDir]] of Object.entries(UNITS)) {
      const unitYaml = readFileSync(join('raw', rawDir, 'unit.yaml'), 'utf8');
      const n = +(unitYaml.match(/^weeks-expected: (\d+)/m)?.[1] ?? 12);
      lines.push(`## ${unit.toUpperCase()}`, '', '| Week | On the site | Transcript in raw/ | Notes |', '| --- | --- | --- | --- |');
      for (let k = 1; k <= n; k++) {
        const id = `${unit}-w${String(k).padStart(2, '0')}`, dir = join('raw', rawDir, `week-${String(k).padStart(2, '0')}`);
        const files = existsSync(dir) ? readdirSync(dir) : [];
        const transcript = files.some((f) => /transcript/i.test(f));
        const wf = existsSync(weekFile(id)) ? readFileSync(weekFile(id), 'utf8') : '';
        const d = wf ? yaml.load(wf.split(/^---$/m)[1] ?? '', { schema: yaml.JSON_SCHEMA }) ?? {} : {};
        const note = (d.thin ? d['thin-reason'] : transcript ? '' : d['source-note']) ?? '';
        lines.push(`| ${k} | ${wf ? (d.thin ? 'yes — thin' : 'yes') : files.length ? 'no — material in raw/, not built' : 'no — nothing released yet'} | ${transcript ? 'yes' : 'no'} | ${String(note).replace(/\s+/g, ' ').replace(/\|/g, '/').trim()} |`);
      }
      lines.push('');
    }
    writeFileSync('docs/pending-material.md', lines.join('\n'));
    console.log(lines.join('\n'));
  } else if (args[0] === '--untag') {
    const weeks = new Set(args.slice(1));
    if (!weeks.size) { console.error('name the week ids, e.g. --untag laws2400-w09'); process.exit(1); }
    let n = 0;
    for (const i of plan()) {
      if (!weeks.has(i.weekId) || !i.exists) continue; // only files that are actually in raw/
      const to = i.src.replace(TAG, '');
      if (existsSync(to)) { console.log(`skip (exists): ${to}`); continue; }
      renameSync(i.src, to); n++;
    }
    console.log(`untagged ${n} file(s); video keeps its tag`);
  } else {
    const items = plan();
    if (!items.length) { console.log('Inbox empty: no tagged, non-video files in the four unit folders.'); process.exit(0); }
    showPlan(items);
    if (args[0] === '--copy') {
      let n = 0;
      for (const i of items) {
        if (!i.dest || i.exists) continue;
        mkdirSync(join(i.dest, '..'), { recursive: true }); copyFileSync(i.src, i.dest); n++;
        // GitHub refuses files over 100 MB: keep it local and gitignored; the week's builder reads it from the deck and
        // commits a "(text extract).md" beside it (scripts/source-hash.mjs skips the original, MAX_RAW_BYTES).
        if (statSync(i.dest).size > 95e6) {
          const gi = readFileSync('.gitignore', 'utf8');
          if (!gi.includes(i.dest)) writeFileSync('.gitignore', gi.replace(/\n*$/, '\n') + i.dest + '\n');
          console.log(`  ! over 95 MB, gitignored: ${i.dest} — commit a "(text extract).md" beside it`);
        }
      }
      console.log(`\ncopied ${n} file(s) into raw/ (originals untouched). Next: /new-material continues with the weeks above.`);
    } else console.log('\n(dry run — add --copy to copy into raw/)');
  }
}
