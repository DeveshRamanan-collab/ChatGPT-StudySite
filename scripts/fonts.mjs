// Copies the self-hosted WOFF2 files from @fontsource-variable into public/fonts and writes
// src/styles/fonts.css with @font-face rules plus metric-matched local fallbacks (size-adjust,
// ascent/descent/line-gap overrides from @capsizecss/metrics) so the swap causes no layout shift.
// Run: npm run fonts (re-run only when font packages change).
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';

const FONTS = [
  { family: 'Fraunces', pkg: 'fraunces', files: [['fraunces-latin-full-normal', 'normal'], ['fraunces-latin-full-italic', 'italic']], weight: '100 900', metrics: 'fraunces', fallback: { metrics: 'georgia', local: ['Georgia', 'Times New Roman'] } },
  { family: 'Inter', pkg: 'inter', files: [['inter-latin-wght-normal', 'normal']], weight: '100 900', metrics: 'inter', fallback: { metrics: 'arial', local: ['Arial', 'Helvetica'] } },
  { family: 'JetBrains Mono', pkg: 'jetbrains-mono', files: [['jetbrains-mono-latin-wght-normal', 'normal']], weight: '100 800', metrics: 'jetBrainsMono', fallback: { metrics: 'courierNew', local: ['Courier New', 'Courier'] } },
];
const LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
const pct = (n) => `${(n * 100).toFixed(2)}%`;
const load = async (n) => (await import(`@capsizecss/metrics/${n}`)).default;

mkdirSync('public/fonts', { recursive: true });
let css = '/* Generated by scripts/fonts.mjs — do not edit by hand. */\n';
for (const f of FONTS) {
  for (const [file, style] of f.files) {
    copyFileSync(`node_modules/@fontsource-variable/${f.pkg}/files/${file}.woff2`, `public/fonts/${file}.woff2`);
    css += `@font-face{font-family:"${f.family}";font-style:${style};font-weight:${f.weight};font-display:swap;src:url(/fonts/${file}.woff2) format("woff2");unicode-range:${LATIN}}\n`;
  }
  const m = await load(f.metrics);
  const fb = await load(f.fallback.metrics);
  const size = m.xWidthAvg / m.unitsPerEm / (fb.xWidthAvg / fb.unitsPerEm);
  const src = f.fallback.local.map((l) => `local("${l}")`).join(',');
  css += `@font-face{font-family:"${f.family} Fallback";src:${src};size-adjust:${pct(size)};ascent-override:${pct(m.ascent / m.unitsPerEm / size)};descent-override:${pct(Math.abs(m.descent) / m.unitsPerEm / size)};line-gap-override:${pct(m.lineGap / m.unitsPerEm / size)}}\n`;
}
writeFileSync('src/styles/fonts.css', css);
console.log(css);
